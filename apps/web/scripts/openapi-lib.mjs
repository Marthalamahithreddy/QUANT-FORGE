/**
 * Shared pieces of the OpenAPI contract tooling: where the files live, how the backend schema is
 * exported, and how the TypeScript types are generated from a snapshot. Imported by the CLI
 * (scripts/openapi.mjs) and by the freshness test (tests/openapi-contract.test.ts), so both use
 * the same generation code.
 */

import { spawnSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

export const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const SNAPSHOT_PATH = resolve(root, "contract/openapi.json");
export const TYPES_PATH = resolve(root, "src/types/generated/api.d.ts");

const HEADER = `/**
 * GENERATED by scripts/openapi.mjs from contract/openapi.json. Do not edit.
 * Refresh: npm run contract:export
 *
 * These are COMPILE-TIME types only. They describe what the backend claims; they prove nothing about
 * a received payload. Runtime validation lives in src/lib/api/decode.ts and src/lib/api/decoders/.
 */

`;

/** The backend's own `create_app().openapi()`, through scripts/export_openapi.py (needs `uv`). */
export function exportBackendSnapshot() {
  const run = spawnSync(
    "uv",
    ["run", "--frozen", "--project", "../api", "python", "scripts/export_openapi.py"],
    { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
  );
  if (run.status !== 0) {
    throw new Error(run.stderr || "Could not export the OpenAPI document from the backend.");
  }
  return run.stdout;
}

/** TypeScript source for a snapshot. Pure: the same snapshot text always yields the same bytes. */
export async function typesFromSnapshot(snapshotText) {
  const ast = await openapiTS(JSON.parse(snapshotText), { alphabetize: true });
  return HEADER + astToString(ast);
}

export function readText(path) {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return null;
  }
}
